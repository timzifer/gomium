// Command cefshim generates the runtime-binding shim for libcef from
// cef_shim_symbols.txt: one assembly trampoline per export (cef_shim.S), the
// pointer table the trampolines jump through (cef_shim.c) and the Go-side
// name list the loader resolves (cef_shim_symbols.go). Slot order in all
// three outputs follows the symbol file - keeping that index contract in a
// single place is the reason the files are generated together.
//
// Outputs land in the working directory, which is internal/cefshim: run it
// as `go generate ./internal/cefshim`, not from the module root.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const symbolFile = "cef_shim_symbols.txt"

var symbolRe = regexp.MustCompile(`^cef_[a-z0-9_]+$`)

func main() {
	outDir := flag.String("out", ".", "directory receiving the generated files (the symbol list is always read from the working directory)")
	flag.Parse()

	syms, err := readSymbols(symbolFile)
	if err != nil {
		fail(err)
	}
	for name, content := range map[string]string{
		"cef_shim.S":          genAsm(syms),
		"cef_shim.c":          genTable(syms),
		"cef_shim_symbols.go": genGo(syms),
	} {
		if err := os.WriteFile(filepath.Join(*outDir, name), []byte(content), 0o644); err != nil {
			fail(err)
		}
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "cefshim:", err)
	os.Exit(1)
}

func readSymbols(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var syms []string
	seen := map[string]bool{}
	sc := bufio.NewScanner(f)
	line := 0
	for sc.Scan() {
		line++
		s := strings.TrimSpace(sc.Text())
		if s == "" || strings.HasPrefix(s, "#") {
			continue
		}
		if !symbolRe.MatchString(s) {
			return nil, fmt.Errorf("%s:%d: %q is not a valid cef export name", path, line, s)
		}
		if seen[s] {
			return nil, fmt.Errorf("%s:%d: duplicate symbol %q", path, line, s)
		}
		seen[s] = true
		syms = append(syms, s)
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(syms) == 0 {
		return nil, fmt.Errorf("%s: no symbols", path)
	}
	return syms, nil
}

func genAsm(syms []string) string {
	var b strings.Builder
	b.WriteString(`/* Code generated by tools/cefshim; DO NOT EDIT. */

/* One tail-jump trampoline per libcef export, jumping through the pointer
   table in cef_shim.c. No prologue, no touched registers, so the trampoline
   is signature-neutral - arguments and return values pass straight through.
   Comments in this file must stay in this form: '#' is both a cpp directive
   and the GAS comment character in a preprocessed .S file. */

/* Mach-O prefixes every C symbol with an underscore, ELF and PE-COFF do not.
   The trampolines carry C linkage names, so the prefix has to be spelled out
   here instead of being left to the assembler. */
#if defined(__APPLE__)
#define CSYM(name) _##name
#else
#define CSYM(name) name
#endif

    .text

#if defined(__x86_64__) || defined(__amd64__)

/* amd64: one indirect jump through the RIP-relative slot. Same encoding for
   ELF, PE-COFF and Mach-O - only the symbol prefix differs. */

`)
	for _, s := range syms {
		fmt.Fprintf(&b, "    .globl CSYM(%s)\n    .p2align 4\nCSYM(%s):\n    jmp *CSYM(__pfn_%s)(%%rip)\n\n", s, s, s)
	}
	b.WriteString(`#elif defined(__aarch64__) || defined(__arm64__)

/* arm64 has no memory-indirect branch, so the slot is loaded first. x16 is
   the intra-procedure-call scratch register - the ABI lets a veneer clobber
   it, which is exactly what this is, so no argument register is touched.

   The slot address itself is taken through the GOT: cef_shim.c is a
   different translation unit, and that is the addressing a compiler would
   emit for a default-visibility global it cannot prove non-preemptible.
   The linker relaxes it to a direct adrp/add pair when it can. */

#if defined(__APPLE__)

`)
	for _, s := range syms {
		fmt.Fprintf(&b, "    .globl CSYM(%s)\n    .p2align 2\nCSYM(%s):\n"+
			"    adrp x16, CSYM(__pfn_%s)@GOTPAGE\n"+
			"    ldr  x16, [x16, CSYM(__pfn_%s)@GOTPAGEOFF]\n"+
			"    ldr  x16, [x16]\n    br   x16\n\n", s, s, s, s)
	}
	b.WriteString(`#else

/* ELF, and never Mach-O here, so the C names are the linkage names. */

`)
	for _, s := range syms {
		fmt.Fprintf(&b, "    .globl %s\n    .p2align 2\n%s:\n"+
			"    adrp x16, :got:__pfn_%s\n"+
			"    ldr  x16, [x16, #:got_lo12:__pfn_%s]\n"+
			"    ldr  x16, [x16]\n    br   x16\n\n", s, s, s, s)
	}
	b.WriteString(`#endif

#else
#error "gomium: cef_shim.S has trampolines for amd64 and arm64 only"
#endif

#ifdef __ELF__
    .section .note.GNU-stack, "", @progbits
#endif
`)
	return b.String()
}

func genTable(syms []string) string {
	var b strings.Builder
	b.WriteString(`/* Code generated by tools/cefshim; DO NOT EDIT. */

#include <stdio.h>
#include <stdlib.h>

#include "cef_shim.h"

/* Backstop for a call arriving before gomium.LoadLibcef bound the table.
   The trampoline carries no identity, so no symbol name can be reported
   here - the Go-side guard in verifyAndConfigureLibrary is the primary
   check and reports a clean error instead. */
static void gomium_cef_unbound(void) {
    fprintf(stderr, "gomium: fatal: libcef function called before gomium.LoadLibcef()\n");
    fflush(stderr);
    abort();
}

`)
	for _, s := range syms {
		fmt.Fprintf(&b, "void *__pfn_%s = (void *)gomium_cef_unbound;\n", s)
	}
	b.WriteString("\nstatic void **const gomium_cef_slots[] = {\n")
	for _, s := range syms {
		fmt.Fprintf(&b, "    &__pfn_%s,\n", s)
	}
	b.WriteString(`};

int gomium_cef_slot_count(void) {
    return (int)(sizeof(gomium_cef_slots) / sizeof(gomium_cef_slots[0]));
}

void gomium_cef_bind(int idx, uintptr_t fn) {
    if (idx >= 0 && idx < gomium_cef_slot_count()) {
        *gomium_cef_slots[idx] = (void *)fn;
    }
}
`)
	return b.String()
}

func genGo(syms []string) string {
	var b strings.Builder
	b.WriteString(`// Code generated by tools/cefshim; DO NOT EDIT.

package cefshim

// cefShimSymbols lists the libcef exports behind the trampolines in
// cef_shim.S, in slot order: index i is the slot gomium_cef_bind(i, ...)
// fills in cef_shim.c.
var cefShimSymbols = []string{
`)
	for _, s := range syms {
		fmt.Fprintf(&b, "\t%q,\n", s)
	}
	b.WriteString("}\n")
	return b.String()
}
